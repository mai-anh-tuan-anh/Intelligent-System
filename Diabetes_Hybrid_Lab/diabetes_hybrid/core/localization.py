def translate(message, language, **values):
    text = ENGLISH.get(message, message) if language == "en" else message
    return text.format(**values) if values else text


def localize_result(value, language):
    if language != "en":
        return value
    if isinstance(value, dict):
        return {key: localize_result(item, language) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return type(value)(localize_result(item, language) for item in value)
    if isinstance(value, str):
        return translate(value, language)
    return value
