"""Validate per-URL evidence bundles and compile a combined Neo4j knowledge base."""
import argparse
import json
import re
from pathlib import Path
from urllib.parse import urlsplit

KB = Path(__file__).resolve().parent
SEED = KB / "cypher" / "kb_diabet.cypher"
IDENTIFIER = re.compile(r"[A-Za-z_]\w*", re.ASCII)
CLAIM = re.compile(r"[a-z][a-z0-9_.-]*=[a-z0-9_.-]+")


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def index_unique(items, key):
    result = {}
    for item in items:
        value = item[key]
        if not isinstance(value, str) or not value or value in result:
            raise ValueError(f"Empty or duplicate {key}: {value!r}")
        result[value] = item
    return result


def collect():
    concepts = read_json(KB / "concepts.json")
    concept_ids = set(index_unique(concepts, "id"))
    sources, passages, relationships = [], [], []
    for path in sorted((KB / "sources").glob("*.json")):
        bundle = read_json(path)
        source = bundle["source"]
        if source["id"] != path.stem or urlsplit(source["url"]).scheme != "https":
            raise ValueError(f"Invalid source ID or URL in {path.name}")
        if not source["scope"] or not bundle["passages"]:
            raise ValueError(f"An empty evidence bundle was found in {path.name}")
        local = index_unique(bundle["passages"], "id")
        for passage in local.values():
            about, focus = set(passage["about"]), set(passage["focus"])
            if (passage["source"] != source["id"] or not focus or not focus <= about
                    or not about <= concept_ids
                    or any(not passage[key].strip() for key in ("text", "text_vi", "title", "title_vi"))):
                raise ValueError(f"Invalid passage {passage['id']} in {path.name}")
            claims = passage.get("claims", [])
            if (not isinstance(claims, list)
                    or any(not isinstance(claim, str) or not CLAIM.fullmatch(claim) for claim in claims)
                    or len({claim.split("=", 1)[0] for claim in claims}) != len(claims)):
                raise ValueError(f"Invalid or duplicated scope in {passage['id']}")
        for edge in bundle["relationships"]:
            endpoints = {edge["from"], edge["to"]}
            if (edge["passage"] not in local or not endpoints <= set(local[edge["passage"]]["about"])
                    or not IDENTIFIER.fullmatch(edge["kind"])):
                raise ValueError(f"Invalid evidence-backed edge in {path.name}: {edge}")
        sources.append(source)
        passages.extend(local.values())
        relationships.extend(bundle["relationships"])
    index_unique(sources, "id")
    index_unique(sources, "url")
    index_unique(passages, "id")
    edge_keys = [(edge["from"], edge["kind"], edge["to"]) for edge in relationships]
    if len(set(edge_keys)) != len(edge_keys):
        raise ValueError("Duplicate semantic relationship")
    if sum(source["kind"] == "Web" and source["tier"] in ("Public health", "Supplementary")
           for source in sources) < 5:
        raise ValueError("At least five distinct diabetes web sources are required")
    return {"name": "kb_diabetes", "schema_version": 1, "concepts": concepts,
            "sources": sources, "passages": passages, "relationships": relationships}


def cypher_map(item):
    # Cypher decodes Unicode escapes even when a local shell reads the seed with a legacy code page.
    return "{" + ", ".join(
        key + ": " + json.dumps(value, ensure_ascii=True)
        for key, value in item.items() if value is not None
    ) + "}"


def cypher_statements(data):
    statements = []
    for label, key in (("Concept", "concepts"), ("Source", "sources"), ("Passage", "passages")):
        statements.append(f"CREATE CONSTRAINT {label.lower()}_id IF NOT EXISTS FOR (n:{label}) REQUIRE n.id IS UNIQUE")
        rows = ",\n".join(cypher_map(item) for item in data[key])
        statements.append(f"UNWIND [\n{rows}\n] AS row\nMERGE (n:{label} {{id: row.id}}) SET n = row")
    statements.extend([
        "MATCH (p:Passage), (s:Source {id: p.source}) MERGE (p)-[:FROM_SOURCE]->(s)",
        "MATCH (p:Passage) UNWIND p.about AS concept_id MATCH (c:Concept {id: concept_id}) MERGE (p)-[:ABOUT]->(c)",
    ])
    for item in data["relationships"]:
        start, end, evidence = (json.dumps(item[key]) for key in ("from", "to", "passage"))
        statements.append(f"MATCH (a:Concept {{id: {start}}}), (b:Concept {{id: {end}}}) "
                          f"MERGE (a)-[r:{item['kind']}]->(b) SET r.passage_id = {evidence}")
    return statements


def compile_cypher(data):
    comment = "// Generated by knowledge_base/build_kb.py from knowledge_base/sources. Edit source bundles instead.\n\n"
    return comment + ";\n\n".join(cypher_statements(data)) + ";\n"


def build(check=False):
    data = collect()
    products = {KB / "kb_diabetes.json": json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                SEED: compile_cypher(data)}
    for path, content in products.items():
        if check:
            if path.read_text(encoding="utf-8") != content:
                raise ValueError(f"Regenerate {path.name} with python -m knowledge_base.build_kb")
        else:
            pending = path.with_suffix(path.suffix + ".tmp")
            pending.write_text(content, encoding="utf-8")
            pending.replace(path)
    return data


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that generated files match their source bundles")
    data = build(check=parser.parse_args().check)
    print(f"{data['name']}: {len(data['sources'])} sources, {len(data['passages'])} passages")

