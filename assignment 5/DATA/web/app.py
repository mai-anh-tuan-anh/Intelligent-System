def resolve_project_root() -> Path:
    """Find the Assignment 5 root directory that contains models/data/outputs."""
    candidates: list[Path] = []
    env_root = os.getenv("A5_PROJECT_ROOT")
    if env_root:
        candidates.append(Path(env_root).expanduser().resolve())

    cwd = Path.cwd().resolve()
    candidates.extend([cwd, APP_DIR, cwd.parent, APP_DIR.parent])

    for candidate in candidates:
        if (candidate / "models").exists() and (candidate / "outputs").exists():
            return candidate

    # A friendly fallback: assume app.py itself is in the assignment root.
    return APP_DIR


