@app.post("/api/predict/image")
def api_predict_image():
    dataset = request.form.get("dataset", "fashion_mnist")
    framework = request.form.get("framework", "tensorflow")
    depth = int(request.form.get("depth", "5"))
    image_file = request.files.get("image")

    if dataset not in DATASETS or DATASETS[dataset]["type"] != "image":
        return jsonify({"error": "Invalid image dataset."}), 400
    if framework not in MODEL_LABELS or (dataset, framework, depth) not in MODEL_FILES:
        return jsonify({"error": "Invalid model selection."}), 400
    if image_file is None or not image_file.filename:
        return jsonify({"error": "Please choose an image file."}), 400

    try:
        result = image_prediction(image_file, dataset, framework, depth)
        return jsonify(result)
    except Exception as exc:
        return jsonify({"error": str(exc)}), 500


