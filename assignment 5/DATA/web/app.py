def safe_json(value: Any):
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        return float(value)
    if isinstance(value, np.ndarray):
        return value.tolist()
    return value


def load_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def load_torch_classes():
    import torch
    from torch import nn

    class ImageCNN(nn.Module):
        def __init__(self, in_channels, num_classes, depth=3):
            super().__init__()
            filters = [32, 64, 128, 128, 160] if depth == 5 else [32, 64, 128]
            pool_after = {0, 1} if depth == 3 else {0, 1, 3}
            blocks = []
            for i in range(depth):
                blocks += [
                    nn.Conv2d(in_channels if i == 0 else filters[i-1], filters[i], 3, padding=1, bias=False),
                    nn.BatchNorm2d(filters[i]),
                    nn.ReLU(inplace=True),
                ]
                if i in pool_after:
                    blocks.append(nn.MaxPool2d(2))
            self.features = nn.Sequential(*blocks)
            self.pool = nn.AdaptiveAvgPool2d(1)
            self.dropout = nn.Dropout(0.30)
            self.classifier = nn.Linear(filters[-1], num_classes)

        def forward(self, x):
            x = self.features(x)
            x = self.pool(x).flatten(1)
            return self.classifier(self.dropout(x))

    class TabularCNN(nn.Module):
        def __init__(self, num_classes, depth=3):
            super().__init__()
            filters = [32, 64, 128, 128, 160] if depth == 5 else [32, 64, 128]
            pool_after = {0, 1} if depth == 3 else {0, 1, 3}
            blocks = []
            for i in range(depth):
                blocks += [
                    nn.Conv1d(1 if i == 0 else filters[i-1], filters[i], kernel_size=3, padding=1, bias=False),
                    nn.BatchNorm1d(filters[i]),
                    nn.ReLU(inplace=True),
                ]
                if i in pool_after:
                    blocks.append(nn.MaxPool1d(2))
            self.features = nn.Sequential(*blocks)
            self.pool = nn.AdaptiveAvgPool1d(1)
            self.dropout = nn.Dropout(0.30)
            self.classifier = nn.Linear(filters[-1], num_classes)

        def forward(self, x):
            x = x.transpose(1, 2)
            x = self.features(x)
            x = self.pool(x).flatten(1)
            return self.classifier(self.dropout(x))

    return torch, ImageCNN, TabularCNN


def load_model(dataset: str, framework: str, depth: int):
    key = (dataset, framework, int(depth))
    if key in _MODEL_CACHE:
        return _MODEL_CACHE[key]

    path = model_path(*key)
    if not path.exists():
        raise FileNotFoundError(
            f"Model artifact not found: {path}. Run the notebook training cells first."
        )

    if framework == "tensorflow":
        import tensorflow as tf
        model = tf.keras.models.load_model(path, compile=False)
    else:
        torch, ImageCNN, TabularCNN = load_torch_classes()
        if dataset == "diabetes":
            model = TabularCNN(3, depth)
        else:
            in_channels = 1 if dataset == "fashion_mnist" else 3
            num_classes = DATASETS[dataset]["classes"]
            model = ImageCNN(in_channels, num_classes, depth)
        checkpoint = torch.load(path, map_location="cpu")
        state_dict = checkpoint.get("model_state_dict", checkpoint)
        model.load_state_dict(state_dict)
        model.eval()

    _MODEL_CACHE[key] = model
    return model


def preprocess_image(uploaded_file, dataset: str) -> Image.Image:
    """Normalize uploaded images to the dimensions used by the selected model."""
    original = Image.open(uploaded_file).convert("RGB")
    if dataset == "fashion_mnist":
        # Preserve a simple grayscale representation for the 28 x 28 Fashion-MNIST model.
        gray = ImageOps.grayscale(original)
        image = ImageOps.contain(gray, (28, 28))
        canvas = Image.new("L", (28, 28), 0)
        canvas.paste(image, ((28-image.width)//2, (28-image.height)//2))
        return canvas

    image = ImageOps.contain(original, (32, 32))
    canvas = Image.new("RGB", (32, 32), (0, 0, 0))
    canvas.paste(image, ((32-image.width)//2, (32-image.height)//2))
    return canvas


def image_prediction(uploaded_file, dataset: str, framework: str, depth: int):
    image = preprocess_image(uploaded_file, dataset)
    arr = np.asarray(image).astype(np.float32) / 255.0
    if dataset == "fashion_mnist":
        arr = arr[..., None]
        display_arr = np.asarray(image)
    else:
        display_arr = np.asarray(image)

    classes = DATASETS[dataset]["class_names"]

    if framework == "tensorflow":
        model = load_model(dataset, framework, depth)
        if dataset == "fashion_mnist":
            x = arr[None, ...]
        else:
            x = arr[None, ...]
        logits = model.predict(x, verbose=0)
        logits = np.asarray(logits)
        shifted = logits - logits.max(axis=1, keepdims=True)
        probs = np.exp(shifted)
        probs = probs / probs.sum(axis=1, keepdims=True)
        probs = probs[0]
    else:
        torch, _, _ = load_torch_classes()
        model = load_model(dataset, framework, depth)
        if dataset == "fashion_mnist":
            x = torch.from_numpy(arr.transpose(2, 0, 1)).unsqueeze(0).float()
        else:
            x = torch.from_numpy(arr.transpose(2, 0, 1)).unsqueeze(0).float()
        with torch.no_grad():
            logits = model(x)
            probs = torch.softmax(logits, dim=1).cpu().numpy()[0]

    order = np.argsort(probs)[::-1]
    top_k = min(5, len(classes))
    items = [
        {"class_id": int(i), "label": classes[int(i)], "probability": float(probs[int(i)])}
        for i in order[:top_k]
    ]
    return {
        "dataset": dataset,
        "dataset_name": DATASETS[dataset]["name"],
        "framework": framework,
        "framework_name": MODEL_LABELS[framework],
        "depth": int(depth),
        "predicted_class": int(order[0]),
        "predicted_label": classes[int(order[0])],
        "confidence": float(probs[int(order[0])]),
        "top_predictions": items,
        "image_data_url": image_to_data_url(display_arr),
        "input_shape": DATASETS[dataset]["input_shape"],
    }


def image_to_data_url(arr: np.ndarray) -> str:
    image = Image.fromarray(arr.astype(np.uint8))
    buffer = BytesIO()
    image.save(buffer, format="PNG")
    encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
    return f"data:image/png;base64,{encoded}"


