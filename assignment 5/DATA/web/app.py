def diabetes_feature_metadata() -> list[dict[str, Any]]:
    pre = load_diabetes_preprocessor()
    raw = load_diabetes_raw()
    metadata = []
    num_cols = []
    cat_cols = []
    num_imputer = None
    cat_imputer = None
    cat_encoder = None

    for name, transformer, columns in pre.transformers_:
        if name == "num":
            num_cols = list(columns)
            num_imputer = transformer.named_steps.get("imputer")
        elif name == "cat":
            cat_cols = list(columns)
            cat_imputer = transformer.named_steps.get("imputer")
            cat_encoder = transformer.named_steps.get("encoder")

    num_defaults = dict(zip(num_cols, num_imputer.statistics_ if num_imputer is not None else []))
    cat_defaults = dict(zip(cat_cols, cat_imputer.statistics_ if cat_imputer is not None else []))

    cat_options: dict[str, list[str]] = {}
    if cat_encoder is not None:
        for col, categories in zip(cat_cols, cat_encoder.categories_):
            cat_options[col] = [str(x) for x in categories.tolist()[:30]]

    for col in pre.feature_names_in_:
        series = raw[col] if col in raw.columns else None
        dtype = str(series.dtype) if series is not None else "object"
        kind = "numeric" if col in num_cols else "categorical"
        default = num_defaults.get(col, cat_defaults.get(col, ""))
        if pd.isna(default):
            default = ""
        metadata.append({
            "name": col,
            "kind": kind,
            "dtype": dtype,
            "default": safe_json(default),
            "options": cat_options.get(col, []),
        })
    return metadata


def parse_value(value: str, dtype: str):
    value = value.strip()
    if value == "":
        return np.nan
    if "int" in dtype:
        try:
            return int(float(value))
        except Exception:
            return np.nan
    if "float" in dtype or "double" in dtype:
        try:
            return float(value)
        except Exception:
            return np.nan
    return value


def diabetes_prediction(form_data: dict[str, str], framework: str, depth: int):
    pre = load_diabetes_preprocessor()
    metadata = diabetes_feature_metadata()
    row = {}
    for meta in metadata:
        row[meta["name"]] = parse_value(form_data.get(meta["name"], ""), meta["dtype"])

    df = pd.DataFrame([row], columns=[m["name"] for m in metadata])
    processed = pre.transform(df).astype(np.float32)[..., None]
    model = load_model("diabetes", framework, depth)

    if framework == "tensorflow":
        logits = model.predict(processed, verbose=0)
        logits = np.asarray(logits)
        shifted = logits - logits.max(axis=1, keepdims=True)
        probs = np.exp(shifted)
        probs = probs / probs.sum(axis=1, keepdims=True)
        probs = probs[0]
    else:
        torch, _, _ = load_torch_classes()
        with torch.no_grad():
            tensor = torch.from_numpy(processed).float()
            probs = torch.softmax(model(tensor), dim=1).cpu().numpy()[0]

    classes = DATASETS["diabetes"]["class_names"]
    order = np.argsort(probs)[::-1]
    predictions = [
        {"class_id": int(i), "label": classes[int(i)], "probability": float(probs[int(i)])}
        for i in order
    ]
    return {
        "predicted_class": int(order[0]),
        "predicted_label": classes[int(order[0])],
        "confidence": float(probs[int(order[0])]),
        "predictions": predictions,
        "processed_shape": list(processed.shape),
        "raw_feature_count": len(metadata),
        "framework": framework,
        "framework_name": MODEL_LABELS[framework],
        "depth": int(depth),
    }


def figure_manifest() -> list[str]:
    if not FIGURES_DIR.exists():
        return []
    return sorted([p.name for p in FIGURES_DIR.glob("*.png")])


def metrics_summary(df: pd.DataFrame) -> dict[str, Any]:
    if df.empty:
        return {"experiments": 0, "datasets": 0, "models": 0, "mean_accuracy": None}
    return {
        "experiments": int(len(df)),
        "datasets": int(df["dataset"].nunique()),
        "models": int(df["framework"].nunique() * df["conv_layers"].nunique() * df["dataset"].nunique()),
        "mean_accuracy": float(df["accuracy"].mean()),
    }


